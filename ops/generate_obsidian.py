"""Generate Obsidian navigation from builder data without importing the game.

Run from any directory: python ops/generate_obsidian.py
Only maps/ is written. Content files and game state are never changed.
"""

import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = '<!-- Generated by ops/generate_obsidian.py; do not edit. -->'
MAP = 'maps/Elsewhere Map.canvas'
NOTES = 'maps/rooms'


def literals(path, names):
    """Read explicit data assignments; never execute a builder or its imports."""
    result = {}
    for node in ast.parse(path.read_text(encoding='utf-8-sig')).body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id in names:
                    result[target.id] = ast.literal_eval(node.value)
    missing = set(names) - result.keys()
    if missing:
        raise ValueError(f'{path.name}: missing literal assignments: {sorted(missing)}')
    return result


def content(root, relative):
    path = root / relative
    if not path.resolve().is_relative_to((root / 'content').resolve()):
        raise ValueError(f'Content path outside content/: {relative}')
    raw = path.read_text(encoding='utf-8-sig')
    comment = re.search(r'<!--(.*?)-->', raw, re.S)
    fields = dict(re.findall(r'^\s*(\w+):\s*([^\r\n]*)', comment[1], re.M)) if comment else {}
    heading = re.search(r'^# ([^\r\n]+)', raw, re.M)
    return fields, heading[1] if heading else None


def link(path, title):
    return f'[[{path.removesuffix(".md")}|{title}]]'


def load_world(root):
    data = literals(root / 'prospect/world/build_rooms.py', ('ROOMS', 'HUB', 'SPOKES'))
    rooms = {}
    for room_id, title, _description in data['ROOMS']:
        if not re.fullmatch(r'[a-z0-9_]+', room_id) or room_id in rooms:
            raise ValueError(f'Invalid or duplicate room ID: {room_id}')
        path = f'content/rooms/{room_id}.md'
        fields, _ = content(root, path)
        if fields.get('room_id') != room_id:
            raise ValueError(f'{path}: room_id does not match builder')
        rooms[room_id] = dict(title=title, source=path, exits=[], npcs=[], ambient=[], objects=[])

    hub = data['HUB']
    if hub not in rooms:
        raise ValueError(f'Unknown hub: {hub}')
    for spoke, outward, inward in data['SPOKES']:
        if spoke not in rooms or spoke == hub:
            raise ValueError(f'Invalid spoke: {spoke}')
        rooms[hub]['exits'].append((outward[0], spoke))
        rooms[spoke]['exits'].append((inward[0], hub))
    for room in rooms.values():
        directions = [direction for direction, _ in room['exits']]
        if len(directions) != len(set(directions)):
            raise ValueError('Duplicate exit directions in builder')

    npcs = literals(root / 'prospect/world/build_npcs.py', ('NPCS',))['NPCS']
    for npc_id, title, room_id in npcs:
        path = f'content/npcs/{npc_id}.md'
        fields, _ = content(root, path)
        if fields.get('npc_id') != npc_id:
            raise ValueError(f'{path}: npc_id does not match builder')
        rooms[room_id]['npcs'].append((path, title))

    ambient = literals(root / 'prospect/world/build_ambient.py', ('AMBIENT_NPC_IDS', 'AMBIENT_OBJECT_IDS'))
    skipped = []
    for constant, folder, category, id_field in (
        ('AMBIENT_NPC_IDS', 'npcs', 'ambient', 'ambient_id'),
        ('AMBIENT_OBJECT_IDS', 'objects', 'objects', 'object_id'),
    ):
        for entity_id in ambient[constant]:
            path = f'content/ambient/{folder}/{entity_id}.md'
            fields, title = content(root, path)
            if fields.get(id_field) != entity_id or not title:
                raise ValueError(f'{path}: missing title or mismatched ID')
            if fields.get('approval') != 'Approved':
                skipped.append(path)
                continue
            rooms[fields['room']][category].append((path, title))
    return rooms, data, skipped


def room_link(room_id, rooms):
    return link(f'{NOTES}/{room_id}.md', rooms[room_id]['title'])


def entity_sections(room):
    for field, title in (('npcs', 'NPCs'), ('ambient', 'Ambient NPCs'), ('objects', 'Objects')):
        if room[field]:
            yield title, [link(path, label) for path, label in room[field]]


def outputs(root, rooms, data):
    files = {}
    for room_id, room in rooms.items():
        lines = [MARKER, f'# {room["title"]}',
                 link(room['source'], 'Open authored room file'),
                 '## Exits']
        lines.append('\n'.join(f'- **{direction.capitalize()}:** {room_link(target, rooms)}'
                               for direction, target in room['exits']) or 'No builder exits.')
        for title, entries in entity_sections(room):
            lines.extend((f'## {title}', '\n'.join(f'- {entry}' for entry in entries)))
        lines.extend(('---', link(MAP, 'Elsewhere Map') + ' · ' + link('maps/README.md', 'Map guide'),
                      'Generated from builder definitions and approved ambient content. '
                      'This is a source-data reference, not a live game snapshot or new setting canon.'))
        files[f'{NOTES}/{room_id}.md'] = '\n\n'.join(lines) + '\n'

    canvas_path = root / MAP
    previous = json.loads(canvas_path.read_text(encoding='utf-8-sig')) if canvas_path.exists() else {}
    old_nodes = {node['id']: node for node in previous.get('nodes', [])}
    old_edges = {edge['id']: edge for edge in previous.get('edges', [])}
    nodes, edges = [], []
    # Existing room positions are retained. New rooms go in a separate grid to
    # the right; this is a layout choice, not invented world geography.
    right = max((n.get('x', 0) + n.get('width', 360) for n in old_nodes.values()), default=-200) + 200
    new_count = 0
    for room_id, room in rooms.items():
        text = [f'## {room_link(room_id, rooms)}', link(room['source'], 'Room file')]
        text.extend(f'**{title}:** ' + ' · '.join(entries) for title, entries in entity_sections(room))
        old = old_nodes.get(room_id, {})
        if old:
            x, y = old['x'], old['y']
        else:
            x, y = right + (new_count % 3) * 560, (new_count // 3) * 420
            new_count += 1
        nodes.append(dict(id=room_id, type='text', text='\n\n'.join(text), x=x, y=y,
                          width=old.get('width', 360), height=old.get('height', 240), color=old.get('color', '5')))
    legend = old_nodes.get('legend', {})
    nodes.append(dict(id='legend', type='text', x=legend.get('x', -560), y=legend.get('y', -400),
                      width=legend.get('width', 360), height=legend.get('height', 260),
                      text='## Elsewhere\n\nRoom titles open generated navigation notes. '
                           'Room file links open authored content.\n\nExit labels: outward from the hub / return. '
                           'Placement is schematic.\n\nBuilder data, not live game state.\n\n'
                           '[[maps/README|Map guide and regeneration]]'))
    sides = {'north': ('top', 'bottom'), 'south': ('bottom', 'top'),
             'east': ('right', 'left'), 'west': ('left', 'right')}
    for spoke, outward, inward in data['SPOKES']:
        edge_id = f'exit_{spoke}'
        old = old_edges.get(edge_id, {})
        start, end = sides.get(outward[0], ('right', 'bottom'))
        edges.append(dict(id=edge_id, fromNode=data['HUB'], toNode=spoke,
                          fromSide=old.get('fromSide', start), toSide=old.get('toSide', end),
                          fromEnd='arrow', toEnd='arrow', label=f'{outward[0]} / {inward[0]}'))
    files[MAP] = json.dumps(dict(nodes=nodes, edges=edges), ensure_ascii=False, indent=2) + '\n'
    return files


def generate(root=ROOT):
    root = root.resolve()
    rooms, data, skipped = load_world(root)
    files = outputs(root, rooms, data)
    # Validate every target and output before making any edits.
    for relative, body in files.items():
        target = root / relative
        if not target.resolve().is_relative_to((root / 'maps').resolve()):
            raise ValueError(f'Output outside maps/: {relative}')
        if relative.endswith('.md') and target.exists() and not target.read_text(encoding='utf-8-sig').startswith(MARKER):
            raise ValueError(f'Refusing to overwrite a hand-authored note: {relative}')
        for name in re.findall(r'\[\[([^\]|]+)', body):
            name = name if Path(name).suffix else name + '.md'
            if name not in files and not (root / name).is_file():
                raise ValueError(f'Broken link in {relative}: {name}')
    for relative, body in files.items():
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or target.read_text(encoding='utf-8-sig') != body:
            target.write_text(body, encoding='utf-8', newline='\n')
    # Remove only obsolete, generator-owned room notes, never user notes.
    for path in (root / NOTES).glob('*.md'):
        if path.relative_to(root).as_posix() not in files and path.read_text(encoding='utf-8-sig').startswith(MARKER):
            if not path.resolve().is_relative_to((root / NOTES).resolve()):
                raise ValueError(f'Unexpected note path: {path}')
            path.unlink()
    print(f'Generated {len(rooms)} room notes and {MAP}; {len(data["SPOKES"])} two-way connections.')
    for path in skipped:
        print(f'Skipped unapproved ambient content: {path}')
    return files


if __name__ == '__main__':
    generate()
