"""
Invite-only account registration (game-plan.md 6.2's last safeguards-
audit item): a closed-beta gate in front of commands/chargen.py's
CmdScriptedCreate. A single-use code, generated by a Builder+ via the
`geninvite` admin command (commands/admin.py), must be entered before
the "First Awakening" cinematic even starts - this is a plain
administrative check, not part of that authored script, so it's asked
before any of that content runs (see chargen.py's own docstring on
that content boundary).

Codes live on a GLOBAL_SCRIPTS singleton (same pattern as
world/llm_budget.py's spend tracker) since they're server-wide state
with no single player/NPC object to live on, and persist across a
server restart.
"""

import string
from datetime import datetime, timezone
from secrets import choice as _secrets_choice

from evennia import GLOBAL_SCRIPTS

# Excludes visually ambiguous characters (0/O, 1/I/L) - these codes
# are meant to be read aloud or typed from a chat message, not
# copy-pasted.
_CODE_ALPHABET = "".join(c for c in string.ascii_uppercase + string.digits if c not in "01OIL")
_CODE_LENGTH = 8


def _registry():
    return GLOBAL_SCRIPTS.invite_registry


def _codes() -> dict:
    registry = _registry()
    if registry.db.codes is None:
        registry.db.codes = {}
    return registry.db.codes


def _generate_one_code() -> str:
    return "".join(_secrets_choice(_CODE_ALPHABET) for _ in range(_CODE_LENGTH))


def generate_codes(count: int) -> list:
    """Create `count` new unused codes and return them, newest last."""
    codes = _codes()
    new_codes = []
    for _ in range(count):
        code = _generate_one_code()
        while code in codes:  # astronomically unlikely, but never silently drop one
            code = _generate_one_code()
        codes[code] = {"used_by": None, "created": datetime.now(timezone.utc).isoformat()}
        new_codes.append(code)
    return new_codes


def consume_code(raw_code: str, used_by: str) -> bool:
    """
    Marks `raw_code` (case-insensitive, whitespace-trimmed) used by
    `used_by` and returns True, or returns False without changing
    anything if it's missing or already used. Single-use: a second
    attempt with the same code always fails, even by the same person.
    """
    codes = _codes()
    code = (raw_code or "").strip().upper()
    entry = codes.get(code)
    if entry is None or entry["used_by"] is not None:
        return False
    entry["used_by"] = used_by
    entry["used_at"] = datetime.now(timezone.utc).isoformat()
    return True
